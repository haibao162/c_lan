/**
 * @param {character[][]} board
 * @return {boolean}
 */
var isValidSudoku = function(board) {
    let column = new Array(9) // 每一列
    let row = new Array(9) // 每一行·
    let square = new Array(9) // 矩阵
    for(let i = 0;i < 9;i++) {
        column[i] = []
        row[i] = []
        square[i] = []
    }

    for (let i = 0;i < 9;i++) {
        for (let j = 0;j < 9;j++) {
            if (board[i][j] != '.') {
                row[i].push(board[i][j])
                column[j].push(board[i][j])
                const index = Math.floor(i / 3) * 3 + Math.floor(j / 3)
                // console.log(index, 'index')
                square[index].push(board[i][j])
            }
        }
    }

    for(let i = 0;i < 9;i++) {
        let size = new Set(row[i]).size
        if (size != row[i].length) {
            return false
        }
        let size2 = new Set(column[i]).size
        if (size2 != column[i].length) {
            return false
        }
        let size3 = new Set(square[i]).size
        if (size3 != square[i].length) {
            return false
        }
    }
};

